@cache
def get_symmetry_orientations(lattice_system_str:str, 
                              top_layer:tuple)->list:
    global symmetry_dict
    return symmetry_dict[lattice_system_str][top_layer]


@cache
def map_hkl_to_unique_hkl(lattice_system_str:str,
                          top_layer:tuple)->tuple:
    global symmetry_dict
    for unique_hkl, top_layer_list in symmetry_dict[lattice_system_str].items():
        if top_layer in top_layer_list:
            return unique_hkl
    raise ValueError(f"The top_layer {top_layer} is not found in symmetry_dict.")

